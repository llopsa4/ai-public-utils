// Install only the full-set revision approved by the user on 2026-11-24.
import {readFileSync,writeFileSync,readdirSync,mkdirSync,copyFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const dir='art/inbox/A3-full-r1';
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const unchanged=['art/atlas/fighter.png','art/atlas/fighter.json','art/atlas/zombies.png','art/atlas/zombies.json',...readdirSync('art/frames/fighter').map(f=>'art/frames/fighter/'+f)];
const before=Object.fromEntries(unchanged.map(p=>[p,hash(p)]));
const approved=JSON.parse(readFileSync('art/manifest.json'));
const expected=[];for(const [a,count] of Object.entries(approved.figures.keys.scout.anims))for(const f of ['se','ne'])for(let n=0;n<count;n++)expected.push(`${a}_${f}_${n}.png`);
assert.equal(expected.length,66);
assert.deepEqual(readdirSync(`${dir}/candidate/scout`).sort(),[...expected].sort());
mkdirSync('art/inbox/A3-approved-r1/scout',{recursive:true});
for(const f of expected)copyFileSync(`${dir}/candidate/scout/${f}`,`art/inbox/A3-approved-r1/scout/${f}`);
// Preserve manifest formatting and all unrelated values.
let manifest=readFileSync('art/manifest.json','utf8');
manifest=manifest.replace(/("scout":\s*\{\s*"scale":\s*)1/,(_,prefix)=>prefix+'2');
manifest=manifest.replace(/("scout":\s*\{\s*"atlas":\s*"scout",\s*"legacyKey":\s*"survivor_scout",\s*"status":\s*)"placeholder"/,(_,prefix)=>prefix+'"final"');
manifest=manifest.replace(/("survivor_scout":\s*\{\s*"size":\s*)\[18, 38\]/,(_,prefix)=>prefix+'[24, 50]');
const updated=JSON.parse(manifest);
assert.equal(updated.atlases.scout.scale,2);assert.equal(updated.figures.keys.scout.status,'final');assert.deepEqual(updated.keys.survivor_scout.size,[24,50]);
writeFileSync('art/manifest.json',manifest);
execFileSync(process.execPath,['scripts/art/pack.mjs','A3-approved-r1'],{stdio:'inherit'});
execFileSync(process.execPath,['scripts/art/standins.mjs'],{stdio:'inherit'});
const frames=expected.map(file=>{const candidate=hash(`${dir}/candidate/scout/${file}`),installed=hash(`art/frames/scout/${file}`);assert.equal(installed,candidate);return {file,sha256:installed};});
for(const [p,h] of Object.entries(before))assert.equal(hash(p),h,`Unrelated art changed: ${p}`);
const preview=readFileSync(`${dir}/local-preview-root.txt`,'utf8').trim();
for(const f of ['scout.png','scout.json'])assert.equal(hash('art/atlas/'+f),hash(preview+'/art/atlas/'+f),`Approved preview atlas differs: ${f}`);
writeFileSync(`${dir}/installation-checks.json`,JSON.stringify({approved:'2026-11-24, user yes to full-set installation',frames,atlasMatchesApprovedPreview:true,unrelatedArtUnchanged:before,publishedOutputRebuilt:false},null,2));
console.log('Installed 66 byte-identical approved frames; scout atlas matches preview; fighter/zombie atlases unchanged.');
