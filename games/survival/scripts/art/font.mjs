/** glyph(ch) -> 8 rows, each an array of 5 booleans. Unknown characters draw as '?'. */
export function glyph(ch) {
  const rows = raw[ch] ?? raw['?'];
  return rows.split('|').map((r) => [...r].map((c) => c === '#'));
}

/** Width in px of `text` at `scale` (one blank column between glyphs, none after the last). */
export function textWidth(text, scale) {
  return text.length ? (text.length * (GLYPH_W + 1) - 1) * scale : 0;
}
