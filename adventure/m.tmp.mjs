import { chromium } from '@playwright/test';
const dir = process.argv[2];
const browser = await chromium.launch({ args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on('pageerror', e => console.log('pageerror', e.message));
await page.goto('http://127.0.0.1:4173/adventure/?debug');
await page.getByRole('button', { name: 'New game' }).click();
await page.locator('#intro-skip').click();
await page.waitForTimeout(1500);
await page.evaluate(() => { const s = window.adventure.session; const st = structuredClone(s.state); st.room = 'ashways'; st.hero = { x: 300, y: 300, face: 'left', pose: 'stand' };
  st.flags = { hasGauntlet: true, hasNotebook: true, latchFixed: true, alarm: true, kilnCold: true, fought: true, gearChecked: true }; st.inventory = ['gauntlet', 'notebook', 'regulator']; st.bag = { salvage: 12, materials: { 'pressure-coil': 1 }, tonics: 0 }; s.replaceState(st); });
await page.waitForTimeout(4000);
await page.screenshot({ path: `${dir}/m-ashways.png` });
await page.evaluate(() => window.adventure.session.ui.openShop());
await page.waitForTimeout(400);
await page.locator('#shop-buy').click();
await page.screenshot({ path: `${dir}/m-shop.png` });
await browser.close();
