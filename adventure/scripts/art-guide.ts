p();
p(`Sprite sheets in \`art/src/characters/\`: a PNG plus an Aseprite JSON-array file (LibreSprite and Aseprite export it; \`frames[]\` with \`frame\` rectangles and \`duration\` in ms, \`meta.frameTags\` with names and frame ranges). Every frame is **${FRAME}×${FRAME}**, the character standing on the bottom row, centred. An adult stands about 220–232 px tall, a child about 150. The layout of frames in the image is free.`);
