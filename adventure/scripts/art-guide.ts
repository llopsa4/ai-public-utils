p(`- Action-ring icons: \`art/src/icons/<verb>.png\`, square, shown at ${ICON_SIZE}×${ICON_SIZE} (a larger square, such as 48×48, is fine and looks sharper): ${VERBS.map(v => `\`${v}\` (${en[`verb.${v}`]})`).join(', ')}.`);
