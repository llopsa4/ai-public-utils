p();
p('Every image the game loads, what it must contain and where things go in it. Replace a file in `art/src/` with a new one that follows these rules and the game picks it up. Nothing in the code depends on how an image was made.');
p();
p('## Workflow');
p();
p('1. Put the new PNG in `art/src/<folder>/` under the same name (and its `.json` next to it, for sheets).');
p('2. `npm run webp`: rooms, foreground pieces, props and the background people ship as WebP copies of the PNGs.');
p('3. `npm run art:check`: checks sizes, frame layouts, animation tags and strips against what the code expects.');
p('4. `npm run dev` to look at it, then `npm run check` and `npm run e2e`.');
p();
p('**Do not run `npm run art` (or `pixelate`, `rig`, `node art/tent.mjs`, `icons`) after replacing images**: those scripts rebuild the current art from Kiln Courier\'s illustrations and would overwrite the new files. Only `npm run webp` is safe. Once everything is replaced, the generator scripts can be retired.');
p();
p('## Conventions');
p();
p(`- The world is 640×360 units; **all art is drawn at 2×** (rooms are ${ROOM_SIZE.w}×${ROOM_SIZE.h}). Coordinates below are in art pixels, from the top left of the room image.`);
p('- PNG with transparency (8-bit palette or full colour). Pixel-art style, but any style works as long as sizes and anchors hold.');
p('- Characters and objects are **anchored at the bottom centre**: the point that touches the floor. A character\'s feet stand on the bottom row of the frame, centred horizontally.');
p('- Characters face **right** in side views; the game mirrors them for left. There is one view per direction tag (down, side, up); the same drawing may be reused.');
p('- The game scales characters with depth (smaller further back) and tints them with the room\'s light, so draw them evenly lit.');
p();
p('## Rooms');
p();
p(`Each room is one painting, ${ROOM_SIZE.w}×${ROOM_SIZE.h}, in \`art/src/rooms/\`. The reference image next to it shows what the code expects:`);
p();
p('- green: the floor Mara and the others can walk on; red: obstacles on the floor');
p('- yellow: clickable things (purple: hidden secrets) with their ids; blue dots: where Mara stands to use them');
p('- pink: where Mara enters the room; orange crosses: objects drawn over the room (their foot point); white dots: story characters\' feet; small green dots: background people\'s stations');
p('- cyan dashed: walk-behind pieces (see below); white dashed: the hanging name board');
p();
p('A new painting should put the things on the list where the reference image shows them, or the positions in `src/content/rooms.ts` must be moved to match the new painting (hotspot polygons, `walkTo`, the walk area, entries, objects, foreground pieces, `look` effects, crowd stations in `src/content/crowd.ts`). `npm test` checks that the walk area, approach points and stations stay consistent.');
p();
for (const room of Object.values(ROOMS)) {
  const file = ROOM_FILES[room.background];
  await referenceImage(room, file);
  p(`### ${en[`room.${room.id}`] ?? room.id}: \`rooms/${file}.png\``);
  p();
  p(`![${room.id}](spec/${file}.jpg)`);
  p();
  p('| Clickable | Name | Box (x, y, w×h) | Mara stands at |');
  p('| --- | --- | --- | --- |');
  for (const h of room.hotspots) p(`| \`${h.id}\`${h.secret ? ' (secret)' : ''} | ${en[h.name] ?? h.name} | ${box(h.polygon)} | ${h.walkTo ? pt(h.walkTo) : '—'} |`);
  p();
  const extras: string[] = [];
  for (const o of room.objects) {
    const info = sheetInfo(join(ART, 'objects', o.sheet));
    extras.push(`- Object \`objects/${o.sheet}\` (${info.size}, tags ${info.tags.join(', ')}): foot point ${pt(o)}${o.movedTo ? `, moves to ${pt(o.movedTo)}` : ''}. Drawn on top of the room, so the painting should leave that spot free (or show what is behind it).`);
  }
  for (const f of room.foreground ?? []) {
    const s = pngSize(join(ART, 'foreground', `${f.image}.png`));
    extras.push(`- Walk-behind piece \`foreground/${f.image}.png\` (${s.w}×${s.h}, top left at ${pt(f)}): the same pixels as the room painting there, transparent elsewhere. It is drawn in front of anyone standing behind it. Cut it from the new painting.`);
  }
  for (const pr of room.props ?? []) {
    if ('image' in pr) extras.push(`- Animated prop \`props/${pr.image}.png\` (${pr.kind}) at ${pt(pr)}: ${pr.kind === 'gauge' ? 'a needle-less dial (the game draws the needle), centred there' : 'hung from its top edge at that point; it swings'}.`);
  }
  for (const a of room.actors) extras.push(`- ${en[`name.${a.id}`]} stands at ${pt(a)}.`);
  if (room.sign) extras.push(`- The name board hangs from ${pt(room.sign)} (about ${art(room.sign.w)}×${art(room.sign.drop + room.sign.h)}); it is painted by the game, so leave a quiet patch of wall there.`);
  if (room.look?.haze?.length) extras.push(`- Heat shimmer (High quality) over: ${room.look.haze.map(h => box([{ x: h.x, y: h.y }, { x: h.x + h.w, y: h.y + h.h }])).join('; ')}: hot spots in the painting (fires, lamps, pipes).`);
  if (room.ambient?.glows?.length) extras.push(`- Flickering light pools at ${room.ambient.glows.map(g => pt(g)).join(', ')}: lamps, kiln mouths, hearths in the painting.`);
  if (extras.length) { for (const e of extras) p(e); p(); }
}

